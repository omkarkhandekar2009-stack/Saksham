export type Language = 'hi' | 'en' | 'mr';

// Numeral conversion utility for Devanagari script in Hindi and Marathi
const devanagariDigits: { [key: string]: string } = {
  '0': '०',
  '1': '१',
  '2': '२',
  '3': '३',
  '4': '४',
  '5': '५',
  '6': '६',
  '7': '७',
  '8': '८',
  '9': '९',
};

/**
 * Localizes numbers according to selected language.
 * Leaves UDID numbers, technical IDs, and UUIDs unchanged.
 */
export function localizeNumber(val: number | string | undefined | null, lang: Language): string {
  if (val === undefined || val === null) return '';
  const str = String(val);
  if (lang === 'en') return str;

  // If this is a technical identifier (contains letters, hyphens, or looks like a UDID/ID), don't convert digits
  if (/^[a-zA-Z0-9_-]{12,}$/.test(str) || /^UDID-[a-zA-Z0-9-]+$/i.test(str) || /^std-\d+$/i.test(str) || /^prof-\d+$/i.test(str)) {
    return str;
  }

  // Convert digits to Devanagari numerals for Hindi and Marathi
  return str.replace(/[0-9]/g, (d) => devanagariDigits[d] || d);
}

/**
 * Localizes percentage strings (e.g. 96.4% -> ९६.४%)
 */
export function localizePercent(val: number | string, lang: Language): string {
  const numStr = typeof val === 'number' ? `${val}%` : val.includes('%') ? val : `${val}%`;
  return localizeNumber(numStr, lang);
}

