/**
 * Universal translation getter function with Devanagari fallback logic.
 */
export function getTranslation(key: string, lang: Language = 'hi'): string {
  const dict = i18n[lang] || i18n.hi;
  if (dict[key]) return dict[key];

  // Fallback to Hindi if English/Marathi is missing
  if (i18n.hi[key]) return i18n.hi[key];

  // Final fallback to English
  if (i18n.en[key]) return i18n.en[key];

  return key;
}
